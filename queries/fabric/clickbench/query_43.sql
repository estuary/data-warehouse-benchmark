SELECT
  DATETRUNC(MINUTE, EventTime) AS M,
  COUNT_BIG(*) AS PageViews
FROM hits
WHERE
  CounterID = 62
  AND EventDate >= '2013-07-14'
  AND EventDate <= '2013-07-15'
  AND IsRefresh = 0
  AND DontCountHits = 0
GROUP BY
  DATETRUNC(MINUTE, EventTime)
ORDER BY
  CASE WHEN DATETRUNC(MINUTE, EventTime) IS NULL THEN 1 ELSE 0 END, DATETRUNC(MINUTE, EventTime)
OFFSET 1000 ROWS
FETCH FIRST 10 ROWS ONLY
